import json, re
SP='/tmp/claude-0/-home-user-SolexVK/1042ddd1-6021-5ed8-9c40-c636930d1ae6/scratchpad/'
base=json.load(open(SP+'base_keys.json'))
en=[l.rstrip('\n') for f in ('en_part1.txt','en_part2.txt','en_part3.txt') for l in open(f,encoding='utf-8')]
assert len(en)==len(base)
d={k:v for k,v in zip(base,en) if k!=v and v not in ('е','копи')}
EXTRA={'Вправо.':'Right.','Встаём.':'Stand up.','К стене.':'To the wall.','На носки.':'Onto the toes.','Назад.':'Back.',
 'Правая вниз.':'Right heel down.','Правая рука, левая нога.':'Right arm, left leg.','Правое колено.':'Right knee.',
 'Вдох, вверх.':'Breathe in, up.','Раз.':'One.','Девять.':'Nine.','Десять.':'Ten.','Одиннадцать.':'Eleven.','Двенадцать.':'Twelve.',
 'Тринадцать.':'Thirteen.','Четырнадцать.':'Fourteen.','Пятнадцать.':'Fifteen.','Шестнадцать.':'Sixteen.'}
def tr(p): return d.get(p) or EXTRA.get(p)
keys=json.load(open('keys.json'))
miss=set()
for k in keys:
    if k in d or k in base: continue
    parts=re.findall(r'[^.]+\.', k)
    out=[]
    for i,p in enumerate(parts):
        p=p.strip(); v=tr(p)
        if not v: miss.add(p); break
        out.append(v)
    else: d[k]=' '.join(out)
print('missing',miss,'total',len(d))
js='// English dictionary. Key = Russian text. Generated by tools/i18n/build_en.py from en_part*.txt.\nexport default '+json.dumps(d,ensure_ascii=False,indent=0)+';\n'
open('/home/user/SolexVK/docs/js/lang/en.js','w',encoding='utf-8').write(js)
