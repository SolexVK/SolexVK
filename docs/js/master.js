export function offlineAnswer(text) {
  const q = String(text || '');
  if (/сегодня|план|что делать|что у меня|today|plan|what.*do/i.test(q)) {
    const ci = courseInfo();
    const d = peekDay(dateStr()) || {};
    const left = ['morning', 'day', 'evening'].filter((k) => !d.sessions?.[k]?.done).map((k) => t(SESSION_META[k].title).toLowerCase());
    return `${t('Сегодня день')} ${ci.dayN}${t(', неделя')} ${ci.week}. ${left.length ? `${t('Осталось:')} ${left.join(', ')}.` : t('Все три занятия сделаны, отдыхайте.')} ${t('Перед занятием измерьте давление.')}`;
  }
  for (const [re, ans] of FAQ) if (re.test(q)) return ans;
  return t('В базовом режиме я отвечаю только на вопросы по курсу: упражнения, давление, боль, питание, сон. Для свободного разговора подключите сервер или ключ API в настройках.');
}
