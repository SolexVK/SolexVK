export function stepSeconds(s) {
  const intro = s.say ? 3 + s.say.length * 0.07 : 0;
  if (s.kind === 'talk') return intro;
  if (s.kind === 'breath') return intro + s.cycles * (s.inh + s.exh) + (s.lead || 0);
  if (s.kind === 'timer' || s.kind === 'walk') return intro + s.dur;
  if (s.kind === 'reps') return intro + (s.lead || 0) + s.reps * s.tempo.reduce((a, p) => a + p.dur, 0);
  return intro;
}

export function minutesWord(sec) {
  const m = Math.floor(sec / 60);
  const s = sec % 60;
  const mw = m === 1 ? 'одна минута' : m >= 2 && m <= 4 ? `${['', '', 'две', 'три', 'четыре'][m]} минуты` : `${m} минут`;
  return s ? `${mw} ${s} секунд` : mw;
}

