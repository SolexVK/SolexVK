export function courseInfo(date = dateStr()) {
  const dayN = Math.max(1, daysBetween(state.profile.startDate, date) + 1);
  const week = Math.ceil(dayN / 7);
  const phase = PHASES.find((p) => week >= p.weeks[0] && week <= p.weeks[1]) || PHASES[2];
  return { dayN, week, phase, planWeek: Math.min(Math.max(week, 1), 4), beyond: week > 4 };
}

