// Удержание с отдыхом: планки, растяжки. between — фраза перед следующим подходом или сменой стороны.
function holds(sec, sets, between, restSec = 15) {
  const sw = between === 'Смените сторону.' || between === 'Смените ногу.';
  const cues = sec >= 30 ? [{ at: Math.round(sec / 2 / 5) * 5, text: 'Дыхание свободное.' }] : [];
  const out = [say(holdFor(sec)), { t: 'hold', dur: sec, cues }];
  for (let i = 1; i < sets; i++) {
    if (sw) out.push(say(between), gap(restSec, 'смена стороны'), say(holdFor(sec)));
    else out.push(say('Отдых.'), gap(restSec, 'отдых'), say(between));
    out.push({ t: 'hold', dur: sec, cues });
  }
  return out;
}

