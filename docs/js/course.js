// ---- язык сценария ----
// Шаг занятия — это список атомарных реплик мастера:
//   say  — фраза-инструкция, мастер договаривает её до конца;
//   beat — такт: фраза (счёт, «вдох»), затем пауза до конца такта;
//   hold — удержание позы с таймером и подсказками по ходу.
export const NUMS = ['Раз', 'Два', 'Три', 'Четыре', 'Пять', 'Шесть', 'Семь', 'Восемь', 'Девять', 'Десять', 'Одиннадцать', 'Двенадцать'];
const num = (n) => `${NUMS[n - 1]}.`;
const say = (...texts) => texts.map((text) => ({ t: 'say', text }));
const gap = (dur, label = 'займите положение') => ({ t: 'beat', text: null, dur, label });

// Простой счёт: «Раз. Два. …», один счёт — одно движение.
function count(n, dur, label) {
  return Array.from({ length: n }, (_, i) => ({ t: 'beat', text: num(i + 1), dur, rep: i + 1, label }));
}

// Повтор из нескольких фаз. Первые guided повторов мастер проговаривает полностью,
// дальше — номер повтора и короткие слова фаз.
function cycle(reps, phases, guided = 1) {
  const out = [];
  for (let r = 1; r <= reps; r++) {
    phases.forEach((ph, k) => {
      let text = r <= guided ? ph.first : (typeof ph.say === 'function' ? ph.say(r) : ph.say);
      if (k === 0 && r > guided && ph.numbered !== false) text = `${num(r)} ${text}`.trim();
      out.push({ t: 'beat', text, dur: ph.dur, rep: r, breath: ph.breath });
    });
  }
  return out;
}

// Дыхание: «Вдох» — «Выдох, раз».
function breathing(cycles, inh, exh, counted = cycles) {
  const out = [];
  for (let c = 1; c <= cycles; c++) {
    out.push({ t: 'beat', text: c <= counted ? 'Вдох.' : null, dur: inh, rep: c, breath: 'in' });
    out.push({ t: 'beat', text: c <= counted ? `Выдох. ${NUMS[c - 1] || ''}.`.replace(' .', '.') : null, dur: exh, rep: c, breath: 'out' });
  }
  return out;
}

function step(def) {
  const items = def.items.flat(Infinity);
  const reps = items.reduce((m, it) => Math.max(m, it.rep || 0), 0);
  return { kind: 'move', ...def, items, reps: def.reps ?? reps };
}

