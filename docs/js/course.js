// plan — параметры из программы ученика (program.resolvePlan). mode: full | light | rest.
export function buildSession(kind, planOrWeek, mode = 'full') {
  const p = typeof planOrWeek === 'object' && planOrWeek ? planOrWeek : defaultPlan(planOrWeek || 1);
  const light = mode === 'light';
  const rest = mode === 'rest';
  const steps = [];
  const talk = (id, title, text, ...lines) => steps.push(step({ id, title, kind: 'talk', text, items: say(...lines) }));
  const keep = (list) => list.filter((st) => !p.exclude.has(st.id));

  if (kind === 'morning') {
    talk('hello', 'Утренний комплекс', 'Двигаемся медленно и без боли. Головокружение или резкая боль — остановитесь.',
      ...(rest
        ? ['Доброе утро. Сегодня день восстановления: только дыхание и мягкое завершение.']
        : light
          ? ['Доброе утро. Сегодня работаем мягко: дыхание и суставная разминка.']
          : ['Доброе утро. Начинаем утренний комплекс.', 'Двигаемся медленно, без боли. Если закружится голова или появится резкая боль, остановитесь.']));
    steps.push(step({ id: 'breath', title: 'Настройка и дыхание', group: 'Настройка', kind: 'breath',
      text: 'Стопы на ширине плеч, колени чуть согнуты, ладони на животе. Вдох носом на 4 счёта, выдох на 6.',
      items: [
        say('Встаньте прямо. Стопы на ширине плеч, носки смотрят вперёд.',
          'Колени чуть согнуты. Макушка тянется вверх, подбородок слегка опущен, плечи расслаблены.',
          'Положите ладони на живот. Дышим носом: на вдохе живот мягко расширяется, выдох длиннее вдоха.'),
        breathing(10, 4, 6),
      ] }));
    if (!rest) steps.push(...keep(warmup(p)));
    if (!light && !rest) {
      const qg = qigong(p);
      if (p.level >= 3) {
        // Уровни 3–4: «Восемь кусков парчи» целиком, затем «Начало тай-чи», шаг и столб.
        const by = Object.fromEntries(qg.map((s) => [s.id, s]));
        steps.push(...keep([by.sky, ...baduanjin(p), by.qishi, ...(p.level === 3 ? [by.shift] : []), catStep(p), by.stolb]));
      } else steps.push(...keep(qg));
    }
    steps.push(closingBreath());
    steps.push(closing(kind));
  }

  if (kind === 'day') {
    if (rest) {
      talk('hello', 'Дневной комплекс', 'Сегодня день восстановления.', 'Сегодня день восстановления. Только разгрузка поясницы.');
    } else {
      const walkMin = p.walkMin;
      const walkSec = walkMin * 60;
      const WORDS = { 5: 'пять', 6: 'шесть', 8: 'восемь', 10: 'десять', 12: 'двенадцать', 15: 'пятнадцать', 18: 'восемнадцать', 20: 'двадцать', 25: 'двадцать пять', 30: 'тридцать' };
      talk('hello', 'Дневной комплекс', 'Ходьба, упражнения для спины и ног, разгрузка поясницы.',
        ...(light
          ? ['Сегодня работаем мягко: только спокойная ходьба и отдых для поясницы.']
          : ['Дневной комплекс. Сначала ходьба, потом упражнения для спины и ног, в конце разгрузка поясницы.', 'Выдох всегда на усилии. Дыхание не задерживаем.']));
      const wc = [];
      const MIN_PAST = { 2: 'Прошли две минуты', 4: 'Прошли четыре минуты', 6: 'Прошло шесть минут', 8: 'Прошло восемь минут' };
      const MIN5 = { 5: 'Прошло пять минут', 10: 'Прошло десять минут', 15: 'Прошло пятнадцать минут', 20: 'Прошло двадцать минут', 25: 'Прошло двадцать пять минут' };
      if (walkMin <= 10) for (let m = 2; m * 60 < walkSec - 60; m += 2) wc.push({ at: m * 60, text: `${MIN_PAST[m]}. Темп такой, чтобы можно было говорить.` });
      else for (let m = 5; m * 60 < walkSec - 60; m += 5) wc.push({ at: m * 60, text: `${MIN5[m]}. Темп такой, чтобы можно было говорить.` });
      wc.push({ at: walkSec - 60, text: 'Осталась одна минута.' });
      steps.push(step({ id: 'walk', title: 'Ходьба', kind: 'hold', dur: walkSec,
        text: light ? 'Идите спокойно, без ускорений.' : 'Темп такой, чтобы стало тепло, но можно было говорить фразами. Телефон можно взять с собой.',
        items: [
          say(walkMin > 10 ? `Прогулка, ${WORDS[walkMin] || walkMin} минут.` : `Ходьба, ${WORDS[walkMin] || walkMin} минут.`, light ? 'Идите спокойно, без ускорений.' : 'Темп такой, чтобы стало тепло, но можно было говорить фразами.'),
          { t: 'hold', dur: walkSec, cues: wc.sort((a, b) => a.at - b.at) },
          say('Ходьба окончена.'),
        ] }));
      if (!light) steps.push(...(p.level >= 3 ? [...strength34(p), ...stretches(p)] : dayStrength(p, 1, 1)));
    }
    if (p.level < 3 || p.gentleBack || light || rest) steps.push(unload(p.unloadCycles, 'Разгрузка поясницы', [p.noFloor
      ? 'Разгрузка поясницы. Лягте на спину на кровать и положите голени на стул или подушки, бёдра вертикально.'
      : 'Разгрузка поясницы. Лягте на спину и положите голени на сиденье стула, бёдра вертикально.']));
    steps.push(closing(kind));
  }

  if (kind === 'evening') {
    talk('hello', 'Перед сном', 'Это не тренировка, а отдых для поясницы.',
      'Вечерняя разгрузка поясницы. Это не тренировка, а отдых.');
    steps.push(unload(24, 'Голени на стуле', [p.noFloor
      ? 'Лягте на спину на кровать и положите голени на стул или подушки, бёдра вертикально.'
      : 'Лягте на спину и положите голени на сиденье стула, бёдра вертикально.']));
    steps.push(closing(kind));
  }

  let dur = steps.reduce((a, s2) => a + stepSeconds(s2), 0);
  // Ограничение по времени из анкеты: убираем сначала наименее важное. Основа занятия остаётся всегда.
  let trimmed = [];
  if (p.maxMin && dur > p.maxMin * 60 * 1.1) {
    let order = TRIM_ORDER[kind] || [];
    if (kind === 'morning') {
      // Движения «Восьми кусков парчи» чередуются по дням: каждый день остаются разные, за неделю — все.
      const n = Math.floor(Date.now() / 86400000) % BDJ.length;
      const rot = [...BDJ.slice(n), ...BDJ.slice(0, n)];
      order = order.flatMap((id) => (id === '*bdj' ? rot : [id]));
    }
    for (const id of order) {
      if (dur <= p.maxMin * 60 * 1.05) break;
      const i = steps.findIndex((s2) => s2.id.replace(/\d+$/, '') === id);
      if (i < 0) continue;
      // Хотя бы два движения «Восьми кусков парчи» остаются всегда.
      if (BDJ.includes(id) && steps.filter((s2) => BDJ.includes(s2.id)).length <= 2) continue;
      dur -= stepSeconds(steps[i]);
      trimmed.push(steps[i].title);
      steps.splice(i, 1);
    }
  }
  return { kind, level: p.level, stage: p.stage, week: p.stage, mode, steps, dur, trimmed };
}

// Оценка длительности шага в секундах.
export function stepSeconds(s) {
  return s.items.reduce((a, it) => {
    if (it.t === 'say') return a + 0.6 + it.text.length * 0.085;
    if (it.t === 'beat') return a + Math.max(it.dur, it.text ? it.text.length * 0.085 + 0.3 : 0);
    if (it.t === 'hold') return a + it.dur;
    return a;
  }, 0);
}

// Все фразы, которые может произнести мастер на занятиях (для озвучки).
export function allSessionTexts() {
  const set = new Set();
  for (const kind of ['morning', 'day', 'evening']) for (const pl of allPlans()) for (const m of ['full', 'light', 'rest']) {
    for (const s of buildSession(kind, pl, m).steps) for (const it of s.items) {
      if (it.text) set.add(it.text);
      for (const c of it.cues || []) set.add(c.text);
    }
  }
  Object.values(SESSION_LINES).forEach((t) => set.add(t));
  return [...set];
}

export function minutesWord(sec) {
  const m = Math.floor(sec / 60);
  const s = sec % 60;
  const SEC = { 15: 'пятнадцать', 30: 'тридцать', 45: 'сорок пять' };
  if (!m) return `${SEC[s] || s} секунд`;
  if (s === 30) return `${['', 'полторы', 'две с половиной', 'три с половиной', 'четыре с половиной', 'пять с половиной', 'шесть с половиной', 'семь с половиной'][m] || `${m} с половиной`} ${m >= 5 ? 'минут' : 'минуты'}`;
  const mw = m === 1 ? 'одна минута' : m >= 2 && m <= 4 ? `${['', '', 'две', 'три', 'четыре'][m]} минуты` : `${{ 5: 'пять', 6: 'шесть', 7: 'семь', 8: 'восемь', 9: 'девять', 10: 'десять' }[m] || m} минут`;
  return s ? `${mw} ${SEC[s] || s} секунд` : mw;
}

