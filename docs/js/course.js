function unload(cycles, title, intro) {
  return step({ id: 'unload', title, group: 'Разгрузка', kind: 'breath',
    text: 'Лёжа на спине, голени на сиденье стула, бёдра вертикально. Вдох на 4 счёта, выдох на 6. Вставать через бок.',
    items: [
      say(...intro, 'Вдох на четыре счёта, выдох на шесть. Поясница расслабляется и опускается к полу.'),
      breathing(cycles, 4, 6, 3),
      say('Хорошо. Вставайте медленно, через бок, опираясь на стул.'),
    ] });
}

export function buildSession(kind, week, mode = 'full') {
  const w = Math.min(Math.max(week, 1), 4);
  const light = mode === 'light';
  const steps = [];
  const talk = (id, title, text, ...lines) => steps.push(step({ id, title, kind: 'talk', text, items: say(...lines) }));

  if (kind === 'morning') {
    talk('hello', 'Утренний комплекс', 'Двигаемся медленно и без боли. Головокружение или резкая боль — остановитесь.',
      ...(light
        ? ['Доброе утро. Давление сегодня повышено, поэтому делаем только дыхание и суставную разминку.']
        : ['Доброе утро. Начинаем утренний комплекс.', 'Двигаемся медленно, без боли. Если закружится голова или появится резкая боль, остановитесь.']));
    steps.push(step({ id: 'breath', title: 'Настройка и дыхание', group: 'Настройка', kind: 'breath',
      text: 'Стопы на ширине плеч, колени чуть согнуты, ладони на животе. Вдох носом на 4 счёта, выдох на 6.',
      items: [
        say('Встаньте прямо. Стопы на ширине плеч, носки смотрят вперёд.',
          'Колени чуть согнуты. Макушка тянется вверх, подбородок слегка опущен, плечи расслаблены.',
          'Положите ладони на живот. Дышим носом: на вдохе живот мягко расширяется, выдох длиннее вдоха.'),
        breathing(10, 4, 6),
      ] }));
    steps.push(...warmup());
    if (!light) steps.push(...qigong(w));
    steps.push(closingBreath());
    steps.push(closing(kind));
  }

  if (kind === 'day') {
    const walkMin = light ? 10 : (w <= 2 ? 8 : 10);
    const walkSec = walkMin * 60;
    talk('hello', 'Дневной комплекс', 'Ходьба, пять упражнений, разгрузка поясницы.',
      ...(light
        ? ['Давление сегодня повышено, поэтому только спокойная ходьба и отдых для поясницы.']
        : ['Дневной комплекс. Сначала ходьба, потом пять упражнений для спины и ног, в конце разгрузка поясницы.', 'Выдох всегда на усилии. Дыхание не задерживаем.']));
    const wc = [];
    const MIN_PAST = { 2: 'Прошли две минуты', 4: 'Прошли четыре минуты', 6: 'Прошло шесть минут', 8: 'Прошло восемь минут' };
    for (let m = 2; m < walkMin; m += 2) wc.push({ at: m * 60, text: `${MIN_PAST[m]}. Темп такой, чтобы можно было говорить.` });
    wc.push({ at: walkSec - 60, text: 'Осталась одна минута.' });
    steps.push(step({ id: 'walk', title: 'Ходьба', kind: 'hold', dur: walkSec,
      text: light ? 'Идите спокойно, без ускорений.' : 'Темп такой, чтобы стало тепло, но можно было говорить фразами. Телефон можно взять с собой.',
      items: [
        say(`Ходьба, ${walkMin === 8 ? 'восемь' : 'десять'} минут.`, light ? 'Идите спокойно, без ускорений.' : 'Темп такой, чтобы стало тепло, но можно было говорить фразами.'),
        { t: 'hold', dur: walkSec, cues: wc.sort((a, b) => a.at - b.at) },
        say('Ходьба окончена.'),
      ] }));
    if (!light) {
      const rounds = 1; // укладываемся в 20 минут: с 3-й недели растёт число повторов, а не кругов
      for (let r = 1; r <= rounds; r++) {
        steps.push(...dayStrength(w, r, rounds));
        if (r < rounds) steps.push(step({ id: `rest${r}`, title: 'Отдых', kind: 'hold', dur: 60, group: `Круг ${r} из ${rounds}`,
          text: 'Минута отдыха. Дышите спокойно.', items: [say('Минута отдыха. Дышите спокойно.'), { t: 'hold', dur: 60, cues: [{ at: 50, text: 'Ещё десять секунд.' }] }] }));
      }
    }
    steps.push(unload(18, 'Разгрузка поясницы', ['Разгрузка поясницы. Лягте на спину и положите голени на сиденье стула, бёдра вертикально.']));
    steps.push(closing(kind));
  }

  if (kind === 'evening') {
    talk('hello', 'Перед сном', 'Это не тренировка, а отдых для поясницы.',
      'Вечерняя разгрузка поясницы. Это не тренировка, а отдых.');
    steps.push(unload(24, 'Голени на стуле', ['Лягте на спину и положите голени на сиденье стула, бёдра вертикально.']));
    steps.push(closing(kind));
  }

  const dur = steps.reduce((a, s) => a + stepSeconds(s), 0);
  return { kind, week: w, mode, steps, dur };
}

// Оценка длительности шага в секундах.
export function stepSeconds(s) {
  return s.items.reduce((a, it) => {
    if (it.t === 'say') return a + 0.6 + it.text.length * 0.085;
    if (it.t === 'beat') return a + Math.max(it.dur, it.text ? it.text.length * 0.085 + 0.3 : 0);
    if (it.t === 'hold') return a + it.dur;
    return a;
  }, 0);
}

// Все фразы, которые может произнести мастер на занятиях (для озвучки).
export function allSessionTexts() {
  const set = new Set();
  for (const kind of ['morning', 'day', 'evening']) for (let w = 1; w <= 4; w++) for (const m of ['full', 'light']) {
    for (const s of buildSession(kind, w, m).steps) for (const it of s.items) {
      if (it.text) set.add(it.text);
      for (const c of it.cues || []) set.add(c.text);
    }
  }
  Object.values(SESSION_LINES).forEach((t) => set.add(t));
  return [...set];
}

export function minutesWord(sec) {
  const m = Math.floor(sec / 60);
  const s = sec % 60;
  if (s === 30) return `${['', 'полторы', 'две с половиной', 'три с половиной', 'четыре с половиной'][m]} минуты`;
  const mw = m === 1 ? 'одна минута' : m >= 2 && m <= 4 ? `${['', '', 'две', 'три', 'четыре'][m]} минуты` : `${m} минут`;
  return s ? `${mw} ${s} секунд` : mw;
}

