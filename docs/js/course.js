// Критерии перехода на этап 2.
export function phase2Criteria(st) {
  let stolb = 0;
  let chair = 0;
  const weekCounts = {};
  for (const [date, d] of Object.entries(st.days)) {
    const m = d.sessions?.morning;
    if (m?.stolbSec) stolb = Math.max(stolb, m.stolbSec);
    const dd = d.sessions?.day;
    if (dd?.chairReps) chair = Math.max(chair, dd.chairReps);
    const wk = Math.floor(daysBetween(st.profile.startDate, date) / 7);
    const n = ['morning', 'day'].filter((k) => d.sessions?.[k]?.done).length;
    weekCounts[wk] = (weekCounts[wk] || 0) + n;
  }
  const bestWeek = Math.max(0, ...Object.values(weekCounts));
  return [
    { ok: stolb >= 240, text: 'Столб 4 минуты без боли', have: stolb ? `лучший результат ${Math.floor(stolb / 60)}:${String(stolb % 60).padStart(2, '0')}` : 'пока нет записей' },
    { ok: chair >= 12, text: '12 вставаний со стула подряд', have: chair ? `лучший результат ${chair}` : 'пока нет записей' },
    { ok: bestWeek >= 10, text: 'Не меньше 10 занятий за неделю', have: `лучшая неделя: ${bestWeek} из 14` },
  ];
}
